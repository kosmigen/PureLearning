"""Build self-hosted, Unicode-ranged reading fonts from Adobe's CN variable fonts.

One-time tooling: pip install 'fonttools[woff]==4.67.0'
Usage: python scripts/subset_reading_fonts.py /path/to/source-fonts
Input filenames and SHA-256 digests are recorded below. Normal site builds do
not need these tools. Every source character remains available, including in
future articles; the browser only downloads the shards a page actually uses.
"""

from collections import Counter
from concurrent.futures import ProcessPoolExecutor
from hashlib import sha256
from io import BytesIO
from pathlib import Path
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = (
    ("Sans", "f971e3bff46f76b49e1d5510556c2297c618ec4b491a295a4e741cdd38257799"),
    ("Serif", "556749ba783b148fa1f48644e8883e5b9351f01abd0d1faad0ba24a21185e76a"),
)


def unicode_ranges(codepoints):
    """Compact adjacent code points without claiming any absent characters."""
    runs = []
    start = end = codepoints[0]
    for point in codepoints[1:]:
        if point == end + 1:
            end = point
        else:
            runs.append((start, end))
            start = end = point
    runs.append((start, end))
    return ",".join(
        f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}"
        for start, end in runs
    )


def build_font(args):
    style, digest, source_dir = args
    path = Path(source_dir) / f"SourceHan{style}CN-VF.ttf.woff2"
    if sha256(path.read_bytes()).hexdigest() != digest:
        raise ValueError(f"Unexpected source font version: {path}")
    font = TTFont(path, lazy=False, recalcTimestamp=False)
    # The OFL reserves "Source"; name the web subsets as derived fonts.
    family = f"PureLearning {style}"
    names = {1: family, 2: "Regular", 3: f"{family} Web 1.0", 4: family,
             6: f"PureLearning{style}", 16: family, 17: "Regular",
             25: f"PureLearning{style}"}
    for record in font["name"].names:
        if record.nameID in names:
            record.string = names[record.nameID].encode(record.getEncoding())
    coverage = set(font.getBestCmap())
    frequency = Counter()
    for doc in sorted((ROOT / "docs").rglob("*.md")):
        frequency.update(map(ord, doc.read_text(encoding="utf-8")))
    # Keep Latin together; group frequently used Chinese together to reduce
    # requests on real pages, then include all remaining source characters.
    latin = sorted(point for point in coverage if point < 0x250)
    remaining = sorted(coverage - set(latin), key=lambda p: (-frequency[p], p))
    groups = [latin] + [sorted(remaining[i:i + 256])
                        for i in range(0, len(remaining), 256)]
    # Decode WOFF2 once. Copying its lazy reader would reconstruct all 30,000
    # glyphs for every shard, even when only a few hundred are needed.
    font.flavor = None
    buffer = BytesIO()
    font.save(buffer)
    decoded = buffer.getvalue()
    output = ROOT / "docs/assets/fonts" / f"reading-{style.lower()}"
    output.mkdir(parents=True, exist_ok=True)
    css = []
    for index, points in enumerate(groups):
        shard = TTFont(BytesIO(decoded), lazy=True, recalcTimestamp=False)
        options = subset.Options()
        options.flavor = "woff2"
        options.hinting = False
        options.recalc_timestamp = False
        options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14, 16, 17, 25]
        options.name_legacy = True
        options.name_languages = ["*"]
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=points)
        subsetter.subset(shard)
        filename = f"{index:03d}.woff2"
        shard.flavor = "woff2"
        shard.save(output / filename)
        css.append(
            f'@font-face {{\n  font-family: "{family}";\n'
            f'  src: url("../fonts/reading-{style.lower()}/{filename}") format("woff2");\n'
            '  font-style: normal;\n  font-weight: 250 900;\n'
            '  font-display: swap;\n'
            f'  unicode-range: {unicode_ranges(points)};\n}}\n'
        )
        if index % 20 == 0:
            print(f"{style}: {index + 1}/{len(groups)} shards", flush=True)
    print(f"{style}: {len(groups)} shards, {len(coverage)} code points", flush=True)
    return "\n".join(css)


if __name__ == "__main__":
    source_dir = Path(sys.argv[1]).resolve()
    with ProcessPoolExecutor(max_workers=2) as pool:
        styles = list(pool.map(build_font, [(s, d, source_dir) for s, d in FONTS]))
    target = ROOT / "docs/assets/stylesheets/reading-fonts.css"
    target.write_text(
        "/* Generated by scripts/subset_reading_fonts.py. SIL OFL 1.1; see fonts/NOTICE.txt. */\n"
        + "\n".join(styles), encoding="utf-8"
    )
